/**
 * prompt_builder.js
 *
 * Назначение: централизованное управление и построение всех текстов промптов, связанных с MCP.
 * Это модуль чистых функций, не зависящий от какого-либо внешнего состояния.
 */

/**
 * Создаёт начальный системный промпт, внедряемый при запуске нового диалога.
 * Этот промпт использует стратегию "многоуровневого обнаружения инструментов".
 *
 * @param {Array<Object>} services - Список сервисов, полученный от MCP Bridge Server; каждый объект содержит { name, description, is_core }.
 * @returns {string} - Полный отформатированный текст промпта.
 */
export function buildInitialPrompt(services) {
    // Группировка сервисов по полю is_core
    const coreServices = services.filter(s => s.is_core === true);
    const otherServices = services.filter(s => s.is_core !== true);
    
    // Основные сервисы: показываем полное описание
    const coreServiceListText = coreServices.length > 0
        ? coreServices.map(s => `- **${s.name}**: ${s.description}`).join('\n')
        : "- Основные сервисы отсутствуют";
    
    // Другие сервисы: показываем только названия
    const otherServiceListText = otherServices.length > 0
        ? otherServices.map(s => `- ${s.name}`).join('\n')
        : "- Другие сервисы отсутствуют";

    return `
# Системные расширенные возможности

Вы интеллектуальный ассистент. Теперь у вас есть возможность вызывать внешние инструменты. 
При получении запроса пользователя вы сначала должны определить, требует ли запрос использования инструментов:
    - Если да: сначала вызовите инструмент, затем объедините вывод инструмента и ответьте пользователю.
    - Если нет: ответьте пользователю напрямую, используя содержимое вашей базы знаний.

## Текущие доступные сервисы

### Основные сервисы (часто используемые функции, полное описание показано)
${coreServiceListText}

### Другие сервисы (используются по необходимости, показаны только названия)
${otherServiceListText}

## Процесс использования инструментов

### Шаг первый: определить, нужен ли инструмент

Глубоко вникните в потребности пользователя и определите, обращается ли он с какими-либо запросами, касающимися инструментов.

### Шаг второй: просмотреть список инструментов сервиса

**Независимо от того, основной это сервис или другой**, после решения использовать какой-либо сервис сначала нужно вызвать \`list_tools_in_service\`, чтобы просмотреть подробную информацию об этом сервисе:

\`\`\`xml
<tool_code>
{
  "tool_name": "list_tools_in_service",
  "arguments": {
    "service_name": "имя сервиса"
  }
}
</tool_code>
\`\`\`

Система вернёт **полную информацию** об этом сервисе, включая:
- **Описание сервиса** (особенно важно для других сервисов, поскольку в начальном промпте оно не показано)
- **Список инструментов**: название, описание и определение параметров каждого инструмента

Затем на основе возвращённого результата выберите подходящий вызов инструмента.

### Шаг третий: вызвать конкретный инструмент

На основе списка инструментов выберите подходящий вызов инструмента:

\`\`\`xml
<tool_code>
{
  "tool_name": "фактическое_имя_инструмента",
  "arguments": {
    "имя_параметра": "значение_параметра"
  },
  "server_name": "имя сервиса"  // Необязательное поле, если нужно указать сервис, используется для различения инструментов с одинаковыми именами
}
</tool_code>
\`\`\`

### Шаг четвёртый: обработка кеша больших результатов

Некоторые инструменты могут возвращать довольно большие результаты (например, содержимое файлов, длинные списки и т. д.). В целях производительности эти результаты кешируются, и вы получите ссылку на кеш.

**Доступные инструменты работы с кешем**:

#### 1. Поиск по содержимому кеша (рекомендуется использовать в первую очередь)
Если пользователю нужно найти определённую информацию, сначала выполните поиск для определения местоположения:

\`\`\`xml
<tool_code>
{
  "tool_name": "search_cached_result",
  "arguments": {
    "cache_id": "ID кеша",
    "keyword": "ключевое слово для поиска",
    "case_sensitive": false,  // Необязательное поле, учитывать ли регистр
    "max_results": 50         // Необязательное поле, максимальное число результатов
  }
}
</tool_code>
\`\`\`

Поиск вернёт номера всех совпавших строк и столбцов, после чего вы сможете точно получить содержимое этих мест.

#### 2. Получение контекста указанной строки
После нахождения целевой строки получите контекст:

\`\`\`xml
<tool_code>
{
  "tool_name": "get_cache_context",
  "arguments": {
    "cache_id": "ID кеша",
    "line_num": 23,          // Номер целевой строки
    "context_lines": 5       // Необязательное поле, количество строк контекста, по умолчанию 3
  }
}
</tool_code>
\`\`\`

#### 3. Поэтапное получение содержимого
Если нужно просмотреть последовательно, получайте небольшими порциями по несколько раз:

\`\`\`xml
<tool_code>
{
  "tool_name": "get_cached_result",
  "arguments": {
    "cache_id": "ID кеша",
    "start": 0,
    "end": 8000    // Рекомендуется по 5000–10000 символов за раз
  }
}
</tool_code>
\`\`\`

**Рекомендуемый порядок**:
1. Получив ссылку на кеш → сначала используйте \`search_cached_result\`, чтобы найти ключевую информацию
2. Найдите целевую позицию → используйте \`get_cache_context\`, чтобы получить контекст
3. Нужно больше содержимого → используйте \`get_cached_result\`, чтобы получать по частям

### Шаг пятый: объединить результаты и ответить

После выполнения инструмента система вернёт вам результат. **Вы должны на основе этих результатов дать пользователю полный, дружелюбный ответ**, а не просто переслать исходные данные.

## Правила вызова

1. **Строгий формат**: XML-тег должен быть \`<tool_code>\`, внутри должен быть допустимый JSON
2. **Один вызов за раз**: за один раз вызывайте только один инструмент, дождитесь результата и только затем решайте следующий шаг
3. **Можно рассуждать**: вы можете в выводе объяснить ход мыслей, например "мне нужно сначала запросить содержимое файла", а затем вывести \`<tool_code>\`
4. **Обычный диалог**: когда инструменты не вызываются, общайтесь естественно, как обычный ассистент
5. **Завершение инструментом**: когда вы решаете вызвать инструмент в этом выводе, ваша команда вызова инструмента \`<tool_code>\` всегда должна находиться в самом конце вашего вывода.

## Обработка ошибок

- Сбой вызова инструмента вернёт сообщение об ошибке; вы можете скорректировать параметры и повторить попытку (не более 3 раз)
- Если решить не удаётся, честно сообщите пользователю причину

---

Теперь начните обрабатывать вопрос пользователя:
`.trim();
}

/**
 * Создаёт краткий напоминающий промпт для сценария «внедрять каждый раз».
 * @returns {string} - Краткий текст напоминания.
 */
export function buildReminderPrompt() {
    return `
# Напоминание о вызове инструментов
Помните, что вы можете вызывать внешние инструменты, выводя конструкцию в формате \`<tool_code>{"tool_name": "...", "arguments": {...}}</tool_code>\`.
`.trim();
}

/**
 * Форматирует результат выполнения инструмента и возвращает его модели.
 *
 * @param {string} toolName - Имя вызванного инструмента.
 * @param {any} toolResult - Результат, возвращённый выполнением инструмента (обычно JSON-объект или строка).
 * @returns {string} - Отформатированный текст результата.
 */
export function formatToolResultForModel(toolName, toolResult) {
    let resultContent;
    try {
        // Пытаемся отформатировать результат как улучшенную JSON-строку, чтобы модели было удобнее читать
        resultContent = typeof toolResult === 'string' ? toolResult : JSON.stringify(toolResult, null, 2);
    } catch (error) {
        resultContent = String(toolResult);
    }

    return `
# Результат выполнения инструмента

**Имя инструмента**: \`${toolName}\`
**Результат выполнения**:
\`\`\`json
${resultContent}
\`\`\`

Теперь, основываясь на результате выполнения инструмента выше, продолжите формировать окончательный ответ для пользователя. При необходимости вы также можете вызвать другой инструмент.
`.trim();
}

/**
 * Когда выполнение инструмента завершается неудачно, создаёт сообщение об ошибке для передачи модели.
 *
 * @param {string} toolName - Имя инструмента, который пытались вызвать.
 * @param {string} errorMessage - Сообщение об ошибке, возвращённое от MCP Bridge Server.
 * @returns {string} - Отформатированный текст сообщения об ошибке.
 */
export function formatToolErrorForModel(toolName, errorMessage) {
    return `
# Сбой выполнения инструмента

**Имя инструмента**: \`${toolName}\`
**Сообщение об ошибке**: ${errorMessage}

Проанализируйте причину ошибки. Вы можете попробовать исправить параметры и снова вызвать этот инструмент, либо выбрать другой инструмент, либо напрямую сообщить пользователю, что задачу выполнить не удалось.
`.trim();
}

/**
 * Форматирует информацию о ссылке на кеш и подсказывает модели, как обрабатывать большие результаты.
 *
 * @param {string} toolName - Имя вызванного инструмента.
 * @param {Object} cacheInfo - Объект информации о кеше, содержащий поля cache_id, cache_type, total_size и т. д.
 * @returns {string} - Отформатированный текст подсказки.
 */
export function formatCachedResultForModel(toolName, cacheInfo) {
    const sizeKB = (cacheInfo.total_size / 1024).toFixed(2);
    
    // В зависимости от размера выдаём рекомендуемый размер порции
    let recommendedChunkSize;
    if (cacheInfo.total_size < 20000) {
        recommendedChunkSize = 5000;
    } else if (cacheInfo.total_size < 100000) {
        recommendedChunkSize = 8000;
    } else {
        recommendedChunkSize = 10000;
    }
    
    return `
# Результат выполнения инструмента (кеширован)

**Инструмент**: \`${toolName}\`  
**Размер**: ${sizeKB} KB (${cacheInfo.total_size} символов)  
**ID кеша**: \`${cacheInfo.cache_id}\`

Результат слишком большой и был кеширован. **Рекомендуемые действия**:

**1. Если пользователю нужно найти определённую информацию** → сначала выполните поиск для определения местоположения:
\`\`\`xml
<tool_code>
{
  "tool_name": "search_cached_result",
  "arguments": {
    "cache_id": "${cacheInfo.cache_id}",
    "keyword": "ключевое слово для поиска"
  }
}
</tool_code>
\`\`\`

**2. Если нужно просмотреть последовательно** → получайте по частям (по ${recommendedChunkSize} символов за раз):
\`\`\`xml
<tool_code>
{
  "tool_name": "get_cached_result",
  "arguments": {
    "cache_id": "${cacheInfo.cache_id}",
    "start": 0,
    "end": ${recommendedChunkSize}
  }
}
</tool_code>
\`\`\`
`.trim();
}